def render_sitemap(pages):
    entries = "\n".join(
        f"""  <url>
    <loc>{loc}</loc>
    <xhtml:link rel="alternate" hreflang="en" href="{loc}"/>
    <xhtml:link rel="alternate" hreflang="fa" href="{loc}?lang=fa"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="{loc}"/>
  </url>"""
        for loc in pages
    )

    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!--
  GENERATED FILE - written by tools/generate_project_pages.py.
  Re-run that script after adding or removing a project; do not edit by hand.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
{entries}
  <url><loc>{SITE_URL}/customer/</loc></url>
</urlset>
"""


# --------------------------------------------------------------------------

def main():
    if not DATA.exists():
        sys.exit(f"{DATA} not found. Run update_projects.py first.")

    data = json.loads(DATA.read_text(encoding="utf-8"))
    groups = data.get("projects", {})
    cdn_base = data.get("cdnBase") or data.get("baseUrl") or ""
    if not cdn_base:
        sys.exit("projects.json has no cdnBase - run update_projects.py first.")

    written = []
    sitemap_pages = [f"{SITE_URL}/"]
    live_dirs = set()

    for category_key, projects in groups.items():
        if category_key not in CATEGORIES:
            print(f"  ! skipping unknown category '{category_key}'")
            continue
        if not projects:
            continue

        entries = []
        for project in projects:
            slug = slugify(folder_from_media(project))
            # Bake the CDN base in - see resolve_media above.
            resolved = dict(project)
            resolved["media"] = [
                {**item, "src": resolve_media(item.get("src", ""), cdn_base)}
                for item in project.get("media", [])
            ]
            entries.append({
                "slug": slug,
                "title": project.get("title", ""),
                "year": project.get("year", ""),
                "cover": resolved["media"][0]["src"] if resolved["media"] else "",
                "project": resolved,
            })

        category_dir = OUT_ROOT / category_key
        category_dir.mkdir(parents=True, exist_ok=True)
        live_dirs.add(category_dir)

        (category_dir / "index.html").write_text(
            render_category_page(category_key, entries), encoding="utf-8"
        )
        sitemap_pages.append(f"{SITE_URL}/work/{category_key}/")
        written.append(f"work/{category_key}/index.html")

        for index, entry in enumerate(entries):
            page_dir = category_dir / entry["slug"]
            page_dir.mkdir(parents=True, exist_ok=True)
            live_dirs.add(page_dir)
            (page_dir / "index.html").write_text(
                render_project_page(entry["project"], category_key, entry["slug"], entries, index),
                encoding="utf-8",
            )
            sitemap_pages.append(f"{SITE_URL}/work/{category_key}/{entry['slug']}/")
            written.append(f"work/{category_key}/{entry['slug']}/index.html")

    # Remove pages for projects that no longer exist, so a renamed folder does
    # not leave a stale URL behind for search engines to keep indexing.
    removed = []
    if OUT_ROOT.exists():
        for path in sorted(OUT_ROOT.glob("*/*")):
            if path.is_dir() and path not in live_dirs:
                shutil.rmtree(path)
                removed.append(str(path.relative_to(ROOT)))
        for path in sorted(OUT_ROOT.glob("*")):
            if path.is_dir() and path not in live_dirs and not any(path.iterdir()):
                path.rmdir()
                removed.append(str(path.relative_to(ROOT)))

    SITEMAP.write_text(render_sitemap(sitemap_pages), encoding="utf-8")

    print(f"Wrote {len(written)} pages:")
    for path in written:
        print(f"  {path}")
    if removed:
        print("Removed stale:")
        for path in removed:
            print(f"  {path}")
    # Duplicate meta descriptions are a real ranking problem: search engines
    # treat near-identical pages as thin content and pick one of them to show.
    # This is a content issue, not a code one, so warn rather than invent text.
    seen = {}
    for cat_projects in groups.values():
        for item in cat_projects:
            desc = (item.get("desc") or "").strip()
            if desc:
                seen.setdefault(desc, []).append(item.get("title", "?"))
    duplicates = {d: t for d, t in seen.items() if len(t) > 1}
    if duplicates:
        print("")
        print("  ! Several projects share the same description, so their pages")
        print("    carry identical meta descriptions and compete with each other.")
        print("    Give each its own desc in data/projects.json - it is the")
        print("    sentence a search result actually shows:")
        for dup_desc, titles in duplicates.items():
            print("      " + ", ".join(titles))
            print('        "' + dup_desc[:64] + '"')

    print(f"\nsitemap.xml now lists {len(sitemap_pages) + 1} URLs.")
    print("\nUpload work/ and sitemap.xml to the web host along with data/projects.json.")


if __name__ == "__main__":
    main()
