def render_project_page(project, category_key, slug, siblings, index):
    meta = CATEGORIES[category_key]
    category_name = meta["en"]
    title = project.get("title", "")
    year = project.get("year", "")
    desc = summarise(project, category_name)
    media = project.get("media", [])
    cover = media[0]["src"] if media else ""

    url = f"{SITE_URL}/work/{category_key}/{slug}/"
    page_title = f"{title}{f' ({year})' if year else ''} — {category_name} by Mehdi Seyfi | Sayfit Studio"

    previous_project = siblings[index - 1] if index > 0 else None
    next_project = siblings[index + 1] if index < len(siblings) - 1 else None

    def sibling_link(entry, key, label_key, fallback):
        if not entry:
            return ""
        return (
            f'<a class="project-page-step" href="../{entry["slug"]}/">'
            f'<span class="project-page-step-label" data-i18n="{label_key}">{fallback}</span>'
            f'<span class="project-page-step-title">{escape(entry["title"])}</span></a>'
        )

    gallery = "\n".join(
        f"""        <figure class="project-page-figure">
          <button class="project-page-shot" type="button" data-index="{i}"
                  data-i18n-attr="aria-label:project.openImage" aria-label="Open image">
            {'<video src="' + escape(item["src"]) + '" muted loop playsinline></video>'
             if item.get("type") == "video" else
             '<img src="' + escape(item["src"]) + '" alt="' + escape(title) + '" loading="' + ("eager" if i == 0 else "lazy") + '" decoding="async">'}
          </button>
        </figure>"""
        for i, item in enumerate(media)
    )

    # VisualArtwork is the closest schema.org type for a sculpture. The
    # BreadcrumbList is what produces the Home > Work > Sculpture trail under
    # the result rather than a bare URL.
    structured = {
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "VisualArtwork",
                "@id": url + "#artwork",
                "name": title,
                "url": url,
                "image": [item["src"] for item in media[:8]],
                "description": desc,
                "artform": category_name,
                "creator": {"@type": "Person", "@id": f"{SITE_URL}/#person", "name": "Mehdi Seyfi"},
                "isPartOf": {"@type": "CollectionPage", "@id": f"{SITE_URL}/work/{category_key}/"},
            },
            {
                "@type": "BreadcrumbList",
                "itemListElement": [
                    {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE_URL + "/"},
                    {"@type": "ListItem", "position": 2, "name": category_name, "item": f"{SITE_URL}/work/{category_key}/"},
                    {"@type": "ListItem", "position": 3, "name": title},
                ],
            },
        ],
    }
    if year:
        structured["@graph"][0]["dateCreated"] = str(year)

    return f"""<!DOCTYPE html>
<!--
  GENERATED FILE - do not edit by hand.

  Written by tools/generate_project_pages.py from data/projects.json.
  Anything you change here is lost the next time that script runs. To change
  the words, edit the project's title/year/desc in data/projects.json; to
  change the layout, edit the template in the script.
-->
<html lang="en" dir="ltr">
<head>
{head_common(3)}

  <title>{escape(page_title)}</title>
  <meta name="description" content="{escape(desc)}">

  <link rel="canonical" href="{url}">
  <link rel="alternate" hreflang="en" href="{url}">
  <link rel="alternate" hreflang="fa" href="{url}?lang=fa">
  <link rel="alternate" hreflang="x-default" href="{url}">

  <meta property="og:type" content="article">
  <meta property="og:site_name" content="Sayfit Studio">
  <meta property="og:url" content="{url}">
  <meta property="og:title" content="{escape(title)} — {escape(category_name)} by Mehdi Seyfi">
  <meta property="og:description" content="{escape(desc)}">
  <meta property="og:image" content="{escape(cover)}">
  <meta property="og:image:alt" content="{escape(title)}">
  <meta property="og:locale" content="en_US">
  <meta property="og:locale:alternate" content="fa_IR">

  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="{escape(title)} — {escape(category_name)}">
  <meta name="twitter:description" content="{escape(desc)}">
  <meta name="twitter:image" content="{escape(cover)}">

  <script type="application/ld+json">
{json.dumps(structured, ensure_ascii=False, indent=2)}
  </script>
</head>

<body class="project-page" data-i18n-pending>
  <noscript>
    <style>
      body[data-i18n-pending] main,
      body[data-i18n-pending] .sticky-nav,
      body[data-i18n-pending] .site-footer {{ visibility: visible; }}
    </style>
  </noscript>

{site_header(3)}

  <main class="project-page-main">
    <nav class="project-page-crumbs" aria-label="Breadcrumb">
      <a href="../../../" data-i18n="project.breadcrumbHome">Home</a>
      <span aria-hidden="true">/</span>
      <a href="../" data-i18n="{meta['i18n']}">{escape(category_name)}</a>
      <span aria-hidden="true">/</span>
      <span aria-current="page">{escape(title)}</span>
    </nav>

    <header class="project-page-head">
      <p class="project-page-year">{escape(year)}</p>
      <h1 class="project-page-title">{escape(title)}</h1>
      <p class="project-page-desc">{escape(project.get('desc', ''))}</p>
      <p class="project-page-count">{len(media)} <span data-i18n="project.imageCount">images</span></p>
    </header>

    <section class="project-page-gallery" aria-label="Gallery">
{gallery}
    </section>

    <nav class="project-page-steps" aria-label="Other projects">
      {sibling_link(previous_project, 'prev', 'project.previous', 'Previous project')}
      {sibling_link(next_project, 'next', 'project.next', 'Next project')}
    </nav>

    <p class="project-page-back">
      <a href="../"><span data-i18n="project.backToCategory">Back to</span>
      <span data-i18n="{meta['i18n']}">{escape(category_name)}</span></a>
    </p>
  </main>

{site_footer()}
{modal_markup()}

  <script type="module" src="../../../js/project-page.js"></script>
</body>
</html>
"""


