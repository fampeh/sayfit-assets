"""
Generates one real HTML page per project, plus the sitemap.

    python tools/generate_project_pages.py

Why this exists
---------------
Every project used to live at the same single URL, injected into the carousel
by JavaScript. Nobody could find "Rostam & Sohrab" by searching for it, nobody
could link to it, and a search engine had one page to index for a body of work
that is actually a dozen separate pieces. This turns each one into an address:

    https://sayfit.ir/work/sculpture/rostam-and-sohrab/

The carousel on the home page is untouched. It stays exactly as it is - these
pages are in addition to it, not instead of it, and the carousel now links into
them.

What it reads
-------------
    data/projects.json    generated by update_projects.py - the source of truth
    i18n/en.json          for the page chrome (nav, footer)
    i18n/fa.json

What it writes
--------------
    work/<category>/<slug>/index.html      one per project
    work/<category>/index.html             one per category, listing its projects
    sitemap.xml                            every page, with hreflang alternates

Safe to run as often as you like: it only ever writes those paths, and it
removes pages whose project has disappeared from projects.json.

Run it AFTER update_projects.py, and upload the generated work/ folder along
with data/projects.json. See docs/PROJECT_PAGES.md.
"""

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "projects.json"
OUT_ROOT = ROOT / "work"
SITEMAP = ROOT / "sitemap.xml"

SITE_URL = "https://sayfit.ir"

# Category key -> the anchor it belongs to on the home page, and the i18n key
# for its visible name. The keys are folder names and must not be renamed; see
# docs/MEDIA.md.
CATEGORIES = {
    "sculpture": {"anchor": "sculpture", "i18n": "work.sculpture", "en": "Sculpture"},
    "tailor-made-glasses": {"anchor": "tailor-made-glasses", "i18n": "work.glasses", "en": "Tailor made glasses"},
    "logo-design": {"anchor": "logo-design", "i18n": "work.identity", "en": "Visual identity"},
}


# --------------------------------------------------------------------------
# Slugs
#
# The URL slug comes from the project's FOLDER name, not its title, because the
# folder name is what update_projects.py derives everything else from and it is
# the one thing guaranteed to be stable.
#
# js/modules/slug.js implements exactly this, so the carousel can work out a
# project's URL in the browser without the slug having to be stored anywhere.
# If you change the rule here, change it there too.
# --------------------------------------------------------------------------

def slugify(name):
    slug = name.lower().replace("&", "-and-")
    slug = re.sub(r"[^a-z0-9]+", "-", slug)
    return slug.strip("-")


def folder_from_media(project):
    """Pull the source folder name out of the first media path."""
    for item in project.get("media", []):
        match = re.search(r"projects/work/[^/]+/([^/]+)/", item.get("src", ""))
        if match:
            return match.group(1)
    return project.get("title", "untitled")


# --------------------------------------------------------------------------
# Media URLs
#
# projects.json stores media paths RELATIVE to the asset repo; the browser
# resolves them against `cdnBase` at runtime. A generated page cannot do that -
# its og:image is read by Telegram and Google, which are not running our
# JavaScript - so the absolute URL has to be baked in here.
# --------------------------------------------------------------------------

def resolve_media(src, cdn_base):
    if not src:
        return ""
    if re.match(r"^[a-z][a-z\d+\-.]*:", src, re.I) or src.startswith("//"):
        return src
    base = cdn_base if cdn_base.endswith("/") else cdn_base + "/"
    return base + src.lstrip("/")


def escape(text):
    return (
        str(text or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def summarise(project, category_name):
    """The meta description. Falls back to something useful if desc is blank."""
    desc = (project.get("desc") or "").strip()
    if desc:
        return desc
    year = project.get("year")
    year_part = f", {year}" if year else ""
    return f"{project.get('title', '')} — {category_name.lower()} by Mehdi Seyfi{year_part}. Sayfit Studio."


# --------------------------------------------------------------------------
# Templates
# --------------------------------------------------------------------------

